const messages: Record<Locale, Copy> = { es, en, it, fr, de };

// El acceso y el registro leen este objeto. El interior de la app lee ui_strings.
export const messageCatalog = messages;

export function isLocale(value: string): value is Locale {
  return locales.includes(value as Locale);
}

export function copy(locale: string): Copy {
  return isLocale(locale) ? messages[locale] : messages.es;
}

export function categoryName(key: string, text: Copy) {
  const label = text[`cat_${key}` as keyof Copy];
  return typeof label === "string" ? label : key;
}
